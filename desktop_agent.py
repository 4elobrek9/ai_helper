def image_to_base64(image) -> str:
    from PIL import Image

    image = image.convert("RGB") if isinstance(image, Image.Image) else image
    if image.width > SCREENSHOT_MAX_WIDTH:
        height = round(image.height * SCREENSHOT_MAX_WIDTH / image.width)
        image = image.resize((SCREENSHOT_MAX_WIDTH, height), Image.Resampling.LANCZOS)
    buffer = io.BytesIO()
    image.save(buffer, format="JPEG", quality=SCREENSHOT_JPEG_QUALITY, optimize=True)
    return base64.b64encode(buffer.getvalue()).decode("ascii")


def _extract_json_object(text: str):
    match = re.search(r"\{.*\}", text, flags=re.DOTALL)
    if not match:
        return None
    try:
        return json.loads(match.group(0))
    except json.JSONDecodeError:
        return None


def _normalize_screen_map(data, image, vision_width: int, vision_height: int):
    if not isinstance(data, dict):
        data = {}
    width, height = image.size
    try:
        reported_width = int(data.get("screen_width") or vision_width)
        reported_height = int(data.get("screen_height") or vision_height)
    except (TypeError, ValueError):
        reported_width, reported_height = vision_width, vision_height
    if reported_width > vision_width * 1.25 or reported_height > vision_height * 1.25:
        reported_width, reported_height = vision_width, vision_height
    sx, sy = width / max(1, reported_width), height / max(1, reported_height)
    elements = []
    raw_elements = data.get("elements", [])
    if not isinstance(raw_elements, list):
        raw_elements = []
    for raw in raw_elements:
        if not isinstance(raw, dict):
            continue
        try:
            x1, y1, x2, y2 = [float(value) for value in raw["bbox"]]
        except (KeyError, TypeError, ValueError):
            continue
        if not all(math.isfinite(value) for value in (x1, y1, x2, y2)):
            continue
        if x2 <= x1 or y2 <= y1:
            continue
        center = raw.get("center")
        try:
            cx, cy = [float(value) for value in center]
        except (TypeError, ValueError):
            cx, cy = (x1 + x2) / 2, (y1 + y2) / 2
        if not math.isfinite(cx) or not math.isfinite(cy):
            cx, cy = (x1 + x2) / 2, (y1 + y2) / 2
        x1, x2, cx = [max(0, min(width - 1, round(value * sx))) for value in (x1, x2, cx)]
        y1, y2, cy = [max(0, min(height - 1, round(value * sy))) for value in (y1, y2, cy)]
        if x2 <= x1 or y2 <= y1:
            continue
        elements.append({
            "id": f"A{len(elements) + 1}",
            "label": str(raw.get("label") or "экранный элемент").strip(),
            "role": str(raw.get("role") or "other").strip().lower(),
            "bbox": [x1, y1, x2, y2],
            "center": [max(x1, min(x2, cx)), max(y1, min(y2, cy))],
            "confidence": max(0.0, min(1.0, _safe_float(raw.get("confidence", 0)))),
            "actionable": bool(raw.get("actionable", False)),
        })
    return {
        "screen_description": str(data.get("screen_description") or "").strip(),
        "application": str(data.get("application") or "").strip(),
        "screen_width": width,
        "screen_height": height,
        "elements": elements,
    }


def get_screen_element(label_or_id: str):
    query = str(label_or_id).strip().lower()
    with _screen_lock:
        for element in _screen_map.get("elements", []):
            if element["id"].lower() == query or element["label"].lower() == query:
                return element
    return None


def _screen_description(screen_map) -> str:
    lines = []
    if screen_map.get("application"):
        lines.append("Приложение: " + screen_map["application"])
    if screen_map.get("screen_description"):
        lines.append("Экран: " + screen_map["screen_description"])
    lines.extend(
        f'{item["id"]} — {item["label"]} [{item["role"]}] '
        f'center={tuple(item["center"])} actionable={item["actionable"]}'
        for item in screen_map.get("elements", [])
    )
    return "\n".join(lines) or "На экране не обнаружено размеченных элементов."


def _safe_float(value) -> float:
    try:
        number = float(value)
        return number if math.isfinite(number) else 0.0
    except (TypeError, ValueError):
        return 0.0


def _ollama_chat(model: str, messages: List[Dict[str, Any]], temperature=0.15):
    response = requests.post(
        f"{OLLAMA_API_BASE}/api/chat",
        json={
            "model": model,
            "messages": messages,
            "stream": False,
            "options": {"temperature": temperature, "num_ctx": 8192},
        },
        timeout=COMMAND_TIMEOUT + 60,
    )
    response.raise_for_status()
    content = response.json().get("message", {}).get("content", "").strip()
    if not content:
        raise RuntimeError(f"Ollama вернул пустой ответ для модели {model}")
    return content


def _analyze_screen(image, task: str) -> str:
    try:
        models = get_ollama_models()
        vision_model = find_vision_model(models)
    except requests.RequestException:
        vision_model = ""
    if vision_model:
        from PIL import Image

        vision_image = image.convert("RGB")
        if vision_image.width > SCREENSHOT_MAX_WIDTH:
            vision_height = round(vision_image.height * SCREENSHOT_MAX_WIDTH / vision_image.width)
            vision_image = vision_image.resize(
                (SCREENSHOT_MAX_WIDTH, vision_height), Image.Resampling.LANCZOS
            )
        answer = _ollama_chat(
            vision_model,
            [
                {"role": "system", "content": VISION_SYSTEM_PROMPT},
                {
                    "role": "user",
                    "content": (
                        f"Задача: {task}\nРазметь полезные для задачи элементы. "
                        "Верни только JSON."
                    ),
                    "images": [image_to_base64(vision_image)],
                },
            ],
            temperature=0.02,
        )
        data = _extract_json_object(answer)
        if data:
            with _screen_lock:
                _screen_map.clear()
                _screen_map.update(_normalize_screen_map(
                    data, image, vision_image.width, vision_image.height
                ))
            return _screen_description(_screen_map)
        return "Локальная Vision-модель вернула неразбираемую карту экрана."

    try:
        import pytesseract
        ocr = pytesseract.image_to_string(image).strip()
    except Exception as exc:
        ocr = f"OCR недоступен: {type(exc).__name__}: {exc}"
    return (
        "Локальная Vision-модель не установлена; доступен только OCR.\n"
        + (ocr[:6000] if ocr else "OCR не обнаружил текст.")
    )


def _extract_code_blocks(text: str) -> List[Tuple[str, str]]:
    blocks = []
    pattern = re.compile(r"```([A-Za-z0-9_+\-]*)\s*\n(.*?)```", re.DOTALL)
    aliases = {
        "ps": "powershell", "pwsh": "powershell", "shell": "powershell",
        "cmd": "powershell", "py": "python", "python3": "python",
    }
    for match in pattern.finditer(text):
        language = aliases.get(match.group(1).strip().lower(), match.group(1).strip().lower())
        code = match.group(2).strip()
        if code and language in {"python", "powershell"}:
            blocks.append((language, code))
    return blocks


def _run_powershell(code: str):
    executable = shutil.which("powershell") or shutil.which("pwsh")
    if not executable:
        return {"ok": False, "stdout": "", "stderr": "PowerShell не найден", "returncode": -1}
    try:
        with tempfile.TemporaryDirectory(prefix="lumi-agent-") as temp_dir:
            script_path = Path(temp_dir) / "agent-step.ps1"
            script_path.write_text(
                "$ErrorActionPreference = 'Stop'\n" + code,
                encoding="utf-8-sig",
            )
            completed = subprocess.run(
                [
                    executable, "-NoLogo", "-NoProfile", "-NonInteractive",
                    "-ExecutionPolicy", "Bypass", "-File", str(script_path),
                ],
                capture_output=True, text=True, encoding="utf-8", errors="replace",
                timeout=COMMAND_TIMEOUT,
            )
        return {
            "ok": completed.returncode == 0,
            "stdout": completed.stdout or "",
            "stderr": completed.stderr or "",
            "returncode": completed.returncode,
        }
    except subprocess.TimeoutExpired as exc:
        return {
            "ok": False,
            "stdout": str(exc.stdout or ""),
            "stderr": f"Превышен таймаут команды ({COMMAND_TIMEOUT} секунд)",
            "returncode": -1,
        }


def _execute(language: str, code: str):
    COMPUTER.last_image = None
    stdout, stderr = io.StringIO(), io.StringIO()
    if language == "powershell":
        if re.search(r"\bcomputer\.", code, flags=re.IGNORECASE):
            return {
                "ok": False,
                "returncode": 2,
                "stdout": "",
                "stderr": "Объект computer доступен только в коде Python, не PowerShell.",
            }
        result = _run_powershell(code)
    else:
        try:
            with contextlib.redirect_stdout(stdout), contextlib.redirect_stderr(stderr):
                exec(compile(code, "<lumi-agent>", "exec"), PYTHON_NAMESPACE, PYTHON_NAMESPACE)
            result = {"ok": True, "returncode": 0, "stdout": stdout.getvalue(),
                      "stderr": stderr.getvalue()}
        except (Exception, SystemExit):
            traceback.print_exc(file=stderr)
            result = {"ok": False, "returncode": 1, "stdout": stdout.getvalue(),
                      "stderr": stderr.getvalue()}
    gui_markers = (
        "computer.", "pyautogui", "mouse.", "keyboard.", "screenshot", "webbrowser",
        "start-process", "explorer.exe", "chrome", "msedge",
    )
    if any(marker in code.lower() for marker in gui_markers):
        try:
            result["image"] = COMPUTER.screenshot()
        except Exception as exc:
            result["screenshot_error"] = str(exc)
    result["stdout"] = str(result.get("stdout", ""))[:MAX_RESULT_CHARS]
    result["stderr"] = str(result.get("stderr", ""))[:MAX_RESULT_CHARS]
    return result


def run_agent_turn(history: List[Dict[str, str]], user_text: str,
                   system_prompt: str = "") -> str:
    messages: List[Dict[str, Any]] = [{"role": "system", "content": SYSTEM_PROMPT}]
    if system_prompt.strip():
        messages.append({"role": "system", "content": "Персона Lumi:\n" + system_prompt.strip()})
    messages.extend(history[-20:])

    vision_text = ""
    if request_is_gui(user_text):
        image = capture_screen()
        if image is not None:
            try:
                vision_text = _analyze_screen(image, user_text)
            except requests.RequestException as exc:
                vision_text = f"Ошибка локального Vision Ollama: {exc}"
        else:
            vision_text = "Не удалось захватить экран; проверьте доступ PyAutoGUI."

    task = user_text
    if vision_text:
        task += "\n\n===== VISION SCREEN ANALYSIS =====\n" + vision_text
    messages.append({"role": "user", "content": task})
    transcript = []
    last_action_fingerprint = None
    repeated_action_count = 0
    no_op_retries = 0
    state_action_performed = False
    for step in range(1, MAX_AGENT_STEPS + 1):
        try:
            answer = _ollama_chat(MAIN_MODEL, messages)
        except requests.RequestException as exc:
            return f"Ошибка подключения к локальной Ollama ({OLLAMA_API_BASE}): {exc}"
        except (ValueError, RuntimeError) as exc:
            return f"Ошибка локальной модели {MAIN_MODEL}: {exc}"
        messages.append({"role": "assistant", "content": answer})
        blocks = _extract_code_blocks(answer)
        if not blocks:
            visible = re.sub(r"```.*?```", "", answer, flags=re.DOTALL).strip()
            if request_changes_state(user_text) and not state_action_performed and no_op_retries < 2:
                no_op_retries += 1
                messages.append({
                    "role": "user",
                    "content": (
                        "Запрошенное изменение еще не выполнено. Не отвечай описанием: "
                        "сгенерируй следующий исполняемый кодовый блок, который реально "
                        "выполнит действие и проверит его результат."
                    ),
                })
                continue
            if visible:
                transcript.append(visible)
            break

        language, code = blocks[0]
        code_changes_state = _code_changes_state(code)
        if request_changes_state(user_text) and not state_action_performed and not code_changes_state:
            no_op_retries += 1
            messages.append({
                "role": "user",
                "content": (
                    "Этот код не выполняет запрошенное изменение. Не повторяй его: "
                    "выполни действие реальным вызовом записи/изменения/запуска, "
                    "затем проверь результат."
                ),
            })
            if no_op_retries >= 3:
                transcript.append("Действие остановлено: модель не предложила код, меняющий состояние.")
                break
            continue
        fingerprint = (language, re.sub(r"\s+", " ", code).strip().lower())
        repeated_action_count = repeated_action_count + 1 if fingerprint == last_action_fingerprint else 0
        if repeated_action_count == 1:
            messages.append({
                "role": "user",
                "content": (
                    "Этот же код уже выполнялся, но результат не подтвердил завершение. "
                    "Не запускай его повторно; прочитай результат предыдущего шага и "
                    "выбери другой способ проверки или исправления."
                ),
            })
            continue
        if repeated_action_count >= 2:
            transcript.append("Остановлено повторение одинакового действия без прогресса.")
            break
        last_action_fingerprint = fingerprint

        result = _execute(language, code)
        if result["ok"] and code_changes_state:
            state_action_performed = True
        transcript.append(f"Шаг {step}: {'выполнено' if result['ok'] else 'ошибка'}")
        output = result.get("stdout", "").strip()
        error = result.get("stderr", "").strip()
        if output:
            transcript.append("Вывод:\n" + output[:1200])
        if error:
            transcript.append("Ошибка:\n" + error[-1200:])
        feedback = (
            f"Результат шага {step}: success={result['ok']}, "
            f"returncode={result['returncode']}\n"
            f"stdout:\n{output or '(пусто)'}\n"
            f"stderr:\n{error or '(пусто)'}\n"
        )
        if result.get("screenshot_error"):
            feedback += "\nОшибка screenshot: " + result["screenshot_error"]
        if result.get("image") is not None and request_is_gui(user_text):
            try:
                vision_text = _analyze_screen(result["image"], user_text)
                feedback += "\n===== VISION SCREEN AFTER ACTION =====\n" + vision_text
            except requests.RequestException as exc:
                feedback += f"\nОшибка локального Vision Ollama: {exc}"
        feedback += (
            "\nЕсли задача выполнена и результат проверен, ответь коротко. "
            "Иначе выполни только следующий необходимый шаг; исправь ошибку, "
            "если команда завершилась неуспешно."
        )
        messages.append({"role": "user", "content": feedback})
    else:
        transcript.append(f"Достигнут лимит в {MAX_AGENT_STEPS} шагов; задача может быть не завершена.")

    final_text = "\n".join(transcript).strip()
    history.extend(({"role": "user", "content": user_text},
                    {"role": "assistant", "content": final_text or "Готово."}))
    return final_text or "Готово."


def diagnose() -> Dict[str, Any]:
    result = {
        "endpoint": OLLAMA_API_BASE,
        "model": MAIN_MODEL,
        "vision_model": "",
        "models": [],
        "screen_available": False,
        "powershell_available": bool(shutil.which("powershell") or shutil.which("pwsh")),
    }
    try:
        result["models"] = get_ollama_models()
        result["vision_model"] = find_vision_model(result["models"])
        result["ollama_available"] = MAIN_MODEL in result["models"]
    except requests.RequestException as exc:
        result["ollama_available"] = False
        result["ollama_error"] = str(exc)
    result["screen_available"] = capture_screen() is not None
    return result
