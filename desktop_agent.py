def get_ollama_models() -> List[str]:
    response = requests.get(f"{OLLAMA_API_BASE}/api/tags", timeout=5)
    response.raise_for_status()
    return [
        str(model.get("name", "")).strip()
        for model in response.json().get("models", [])
        if model.get("name")
    ]


def find_vision_model(models: Optional[List[str]] = None) -> str:
    models = get_ollama_models() if models is None else models
    if REQUESTED_VISION_MODEL:
        for model in models:
            if model.lower() == REQUESTED_VISION_MODEL.lower():
                return model
    for prefix in ("qwen2.5vl", "qwen2.5-vl", "qwen3-vl", "qwen3.2-vl",
                   "llava", "minicpm-v", "moondream", "gemma3", "mistral-small3.1"):
        for model in sorted(models, key=str.lower):
            if model.lower().startswith(prefix):
                return model
    return ""


class DesktopComputer:
    """Thin PyAutoGUI wrapper exposed to code generated by the local model."""

    def __init__(self) -> None:
        self._pyautogui = None
        self._mouse = None
        self._keyboard = None
        self.last_image = None

    def _load_pyautogui(self):
        if self._pyautogui is None:
            try:
                import pyautogui
            except ImportError as exc:
                raise RuntimeError("Для управления компьютером установите pyautogui") from exc
            pyautogui.FAILSAFE = True
            pyautogui.PAUSE = 0.05
            self._pyautogui = pyautogui
        return self._pyautogui

    @property
    def mouse(self):
        if self._mouse is None:
            self._mouse = _Mouse(self)
        return self._mouse

    @property
    def keyboard(self):
        if self._keyboard is None:
            self._keyboard = _Keyboard(self)
        return self._keyboard

    def screenshot(self):
        image = self._load_pyautogui().screenshot()
        self.last_image = image
        return image

    def view(self):
        return self.screenshot()

    def click_screen(self, label_or_id: str, clicks: int = 1, button: str = "left"):
        element = get_screen_element(label_or_id)
        if not element:
            raise ValueError(f"Не найден элемент экрана: {label_or_id}")
        if not element.get("actionable"):
            raise ValueError(f"Элемент нельзя нажать: {label_or_id}")
        x, y = element["center"]
        return self.mouse.click(x, y, clicks=clicks, button=button)

    def move_to_screen(self, label_or_id: str, duration: float = 0.2):
        element = get_screen_element(label_or_id)
        if not element:
            raise ValueError(f"Не найден элемент экрана: {label_or_id}")
        x, y = element["center"]
        return self.mouse.move(x, y, duration=duration)

    def double_click_screen(self, label_or_id: str):
        return self.click_screen(label_or_id, clicks=2)

    def type_text(self, text: str):
        return self.keyboard.write(text)

    def press(self, key: str):
        return self.keyboard.press(key)

    def hotkey(self, *keys: str):
        return self.keyboard.hotkey(*keys)


class _Mouse:
    def __init__(self, computer: DesktopComputer) -> None:
        self.computer = computer

    def click(self, x=None, y=None, clicks=1, interval=0.0, button="left"):
        pg = self.computer._load_pyautogui()
        return pg.click(x=x, y=y, clicks=clicks, interval=interval, button=button)

    def move(self, x: int, y: int, duration=0.2):
        return self.computer._load_pyautogui().moveTo(x, y, duration=duration)

    def drag(self, x: int, y: int, duration=0.5, button="left"):
        pg = self.computer._load_pyautogui()
        return pg.dragTo(x, y, duration=duration, button=button)

    def scroll(self, amount: int):
        return self.computer._load_pyautogui().scroll(amount)


class _Keyboard:
    def __init__(self, computer: DesktopComputer) -> None:
        self.computer = computer

    def write(self, text: str, interval=0.0):
        pg = self.computer._load_pyautogui()
        try:
            text.encode("ascii")
        except UnicodeEncodeError:
            import tkinter

            root = tkinter.Tk()
            root.withdraw()
            try:
                root.clipboard_clear()
                root.clipboard_append(text)
                root.update()
            finally:
                root.destroy()
            return pg.hotkey("ctrl", "v")
        return pg.write(text, interval=interval)

    def press(self, key: str):
        return self.computer._load_pyautogui().press(key)

    def hotkey(self, *keys: str):
        return self.computer._load_pyautogui().hotkey(*keys)


