def _code_changes_state(code: str) -> bool:
    patterns = (
        r"\b(?:write_text|write_bytes|mkdir|touch|unlink|rename|replace)\s*\(",
        r"\bopen\s*\([^,\n]+,\s*['\"][wax+]",
        r"\b(?:Set-Content|Add-Content|New-Item|Remove-Item|Rename-Item|"
        r"Move-Item|Copy-Item|Start-Process|Stop-Process)\b",
        r"\b(?:subprocess\.(?:run|Popen|call|check_call)|"
        r"os\.(?:remove|rename|replace|mkdir|startfile|system)|"
        r"shutil\.(?:copy\w*|move|rmtree))\b",
        r"\b(?:webbrowser\.open|computer\.(?:click_screen|double_click_screen|"
        r"move_to_screen|type_text|press|hotkey)|computer\.mouse\.(?:click|move|drag|scroll)|"
        r"computer\.keyboard\.(?:write|press|hotkey)|"
        r"pyautogui\.(?:click|moveTo|dragTo|scroll|write|press|hotkey))\b",
    )
    return any(re.search(pattern, code, flags=re.IGNORECASE) for pattern in patterns)


